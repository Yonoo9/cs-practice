# Enter nums
a = int(input('Enter 1st num:'))
b = int(input('Enter 2nd num:'))

# Sum func
def slojenie(a,b):
    return a + b

# Subtraction func
def vichit(a,b):
    return a - b

# Multiply func
def umnoj(a,b):
    return a * b

# Output

s = slojenie(a,b)
v = vichit(a,b)
u = umnoj(a,b)

print(s)
print(v)
print(u)
