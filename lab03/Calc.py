# Input nums

a = int(input('Enter first num:'))
b = int(input('Enter second num:'))

# Sum func

def sloj(a, b):
    return a + b

# Substraction func

def vichit(a, b):
    return a - b

# Multiply func

def umnoj(a, b):
    return a * b

# Output

s = sloj(a, b)
v = vichit(a, b)
u = umnoj(a, b)

print(s)
print(v)
print(u)
